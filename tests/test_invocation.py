class TestHashVerification(unittest.TestCase):
    def test_stored_valid_hash_accepted(self):
        identity = _build()
        stored = identity.to_stored_object()
        reparsed = parse_invocation_identity(stored)
        self.assertEqual(reparsed.hash_sha256, identity.hash_sha256)

    def test_malformed_stored_hash_rejected(self):
        stored = _build().to_stored_object()
        stored["hash_sha256"] = "not-a-valid-hash"
        with self.assertRaises(InvocationIdentityError) as ctx:
            parse_invocation_identity(stored)
        self.assertEqual(ctx.exception.reason, "INVOCATION_BAD_HASH")

    def test_uppercase_stored_hash_rejected(self):
        stored = _build().to_stored_object()
        stored["hash_sha256"] = stored["hash_sha256"].upper()
        with self.assertRaises(InvocationIdentityError) as ctx:
            parse_invocation_identity(stored)
        self.assertEqual(ctx.exception.reason, "INVOCATION_BAD_HASH")

    def test_wrong_but_well_formed_hash_mismatch(self):
        stored = _build().to_stored_object()
        stored["hash_sha256"] = "0" * 64
        with self.assertRaises(InvocationIdentityError) as ctx:
            parse_invocation_identity(stored)
        self.assertEqual(ctx.exception.reason, "INVOCATION_HASH_MISMATCH")

    def test_changed_request_without_updated_hash_mismatch(self):
        stored = _build().to_stored_object()
        stored["request"]["model"] = "a-different-model"
        with self.assertRaises(InvocationIdentityError) as ctx:
            parse_invocation_identity(stored)
        self.assertEqual(ctx.exception.reason, "INVOCATION_HASH_MISMATCH")


class TestImmutability(unittest.TestCase):
    def test_frozen_dataclass_rejects_attribute_assignment(self):
        identity = _build()
        with self.assertRaises(FrozenInstanceError):
            identity.hash_sha256 = "tampered"

    def test_mutating_stored_object_does_not_affect_identity(self):
        identity = _build()
        stored = identity.to_stored_object()
        original_hash = identity.hash_sha256
        stored["request"]["model"] = "tampered-model"
        stored["hash_sha256"] = "tampered-hash"
        self.assertEqual(identity.hash_sha256, original_hash)
        self.assertEqual(
            identity.to_stored_object()["request"]["model"],
            "openai/gpt-4o",
        )


class TestRoundTrip(unittest.TestCase):
    def test_build_then_parse_matches(self):
        built = _build(parameters={"temperature": 0.2, "max_tokens": 64})
        reparsed = parse_invocation_identity(built.to_stored_object())
        self.assertEqual(built.hash_sha256, reparsed.hash_sha256)
        self.assertEqual(built.to_stored_object(), reparsed.to_stored_object())

    def test_deepcopy_of_stored_object_is_independent(self):
        built = _build()
        stored = copy.deepcopy(built.to_stored_object())
        stored["request"]["messages"][0]["content"] = "changed"
        self.assertEqual(
            built.to_stored_object()["request"]["messages"][0]["content"],
            "hi",
        )


