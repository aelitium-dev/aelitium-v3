"""Tests for the versioned invocation-identity primitive (engine/invocation.py).

Golden hash vectors were independently precomputed (Python `json.dumps` with
the same canonicalization contract as `engine/canonical.py`, cross-checked
with the system `sha256sum` binary) before being hard-coded here -- never
generated by calling `engine.invocation` itself.
"""

import copy
import math
import unittest
from dataclasses import FrozenInstanceError

from engine.canonical import canonical_json, sha256_hash
from engine.invocation import (
    INVOCATION_FORMAT,
    MODE_SYNC_NON_STREAMING,
    MODE_SYNC_STREAMING,
    SURFACE_ANTHROPIC_MESSAGES,
    SURFACE_LITELLM_COMPLETION,
    SURFACE_OPENAI_CHAT_COMPLETIONS,
    InvocationIdentity,
    InvocationIdentityError,
    build_invocation_identity,
    parse_invocation_identity,
)

# --- golden vector (independently precomputed, see module docstring) ------

_GOLDEN_SURFACE = SURFACE_ANTHROPIC_MESSAGES
_GOLDEN_MODE = MODE_SYNC_NON_STREAMING
_GOLDEN_MODEL = "claude-3-5-sonnet-20241022"
_GOLDEN_MESSAGES = [{"role": "user", "content": "hello"}]
_GOLDEN_PARAMETERS = {"max_tokens": 1024}
_GOLDEN_HASH = (
    "0ea189eb5ec49364fe33a5fd01de1b650537c0952cab0c8efe938d829ea15dce"
)


def _build(**overrides):
    kwargs = dict(
        surface=SURFACE_LITELLM_COMPLETION,
        mode=MODE_SYNC_NON_STREAMING,
        model="openai/gpt-4o",
        messages=[{"role": "user", "content": "hi"}],
        parameters=None,
    )
    kwargs.update(overrides)
    return build_invocation_identity(**kwargs)


class TestConstruction(unittest.TestCase):
    def test_valid_openai_non_streaming(self):
        identity = build_invocation_identity(
            surface=SURFACE_OPENAI_CHAT_COMPLETIONS,
            mode=MODE_SYNC_NON_STREAMING,
            model="gpt-4o",
            messages=[{"role": "user", "content": "hi"}],
        )
        self.assertEqual(identity.format, INVOCATION_FORMAT)
        self.assertEqual(identity.surface, SURFACE_OPENAI_CHAT_COMPLETIONS)
        self.assertEqual(identity.mode, MODE_SYNC_NON_STREAMING)
        self.assertEqual(len(identity.hash_sha256), 64)

    def test_valid_openai_streaming(self):
        identity = build_invocation_identity(
            surface=SURFACE_OPENAI_CHAT_COMPLETIONS,
            mode=MODE_SYNC_STREAMING,
            model="gpt-4o",
            messages=[{"role": "user", "content": "hi"}],
        )
        self.assertEqual(identity.mode, MODE_SYNC_STREAMING)

    def test_valid_anthropic_with_max_tokens(self):
        identity = build_invocation_identity(
            surface=SURFACE_ANTHROPIC_MESSAGES,
            mode=MODE_SYNC_NON_STREAMING,
            model=_GOLDEN_MODEL,
            messages=_GOLDEN_MESSAGES,
            parameters={"max_tokens": 1024},
        )
        self.assertEqual(
            identity.to_stored_object()["request"]["parameters"],
            {"max_tokens": 1024},
        )

    def test_valid_litellm_with_allowed_parameters(self):
        identity = build_invocation_identity(
            surface=SURFACE_LITELLM_COMPLETION,
            mode=MODE_SYNC_NON_STREAMING,
            model="openai/gpt-4o",
            messages=[{"role": "user", "content": "hi"}],
            parameters={
                "temperature": 0.0,
                "max_tokens": 128,
                "top_p": 1.0,
                "seed": 42,
                "stop": ["\n"],
            },
        )
        self.assertEqual(len(identity.hash_sha256), 64)


class TestDeterminism(unittest.TestCase):
    def test_same_semantic_input_same_hash(self):
        a = _build()
        b = _build()
        self.assertEqual(a.hash_sha256, b.hash_sha256)

    def test_object_key_ordering_does_not_affect_hash(self):
        a = _build(messages=[{"role": "user", "content": "hi"}])
        b = _build(messages=[{"content": "hi", "role": "user"}])
        self.assertEqual(a.hash_sha256, b.hash_sha256)

    def test_array_ordering_does_affect_hash(self):
        msg_a = {"role": "user", "content": "first"}
        msg_b = {"role": "assistant", "content": "second"}
        a = _build(messages=[msg_a, msg_b])
        b = _build(messages=[msg_b, msg_a])
        self.assertNotEqual(a.hash_sha256, b.hash_sha256)

    def test_lowercase_64_hex_hash(self):
        identity = _build()
        self.assertRegex(identity.hash_sha256, r"^[0-9a-f]{64}$")

    def test_golden_vector(self):
        identity = build_invocation_identity(
            surface=_GOLDEN_SURFACE,
            mode=_GOLDEN_MODE,
            model=_GOLDEN_MODEL,
            messages=_GOLDEN_MESSAGES,
            parameters=_GOLDEN_PARAMETERS,
        )
        self.assertEqual(identity.hash_sha256, _GOLDEN_HASH)


class TestDomainSeparation(unittest.TestCase):
    def test_same_request_different_surface_different_hash(self):
        a = build_invocation_identity(
            surface=SURFACE_ANTHROPIC_MESSAGES,
            mode=MODE_SYNC_NON_STREAMING,
            model="shared-model",
            messages=[{"role": "user", "content": "hi"}],
        )
        b = build_invocation_identity(
            surface=SURFACE_LITELLM_COMPLETION,
            mode=MODE_SYNC_NON_STREAMING,
            model="shared-model",
            messages=[{"role": "user", "content": "hi"}],
        )
        self.assertNotEqual(a.hash_sha256, b.hash_sha256)

    def test_openai_streaming_vs_non_streaming_different_hash(self):
        common = dict(
            surface=SURFACE_OPENAI_CHAT_COMPLETIONS,
            model="gpt-4o",
            messages=[{"role": "user", "content": "hi"}],
        )
        a = build_invocation_identity(mode=MODE_SYNC_NON_STREAMING, **common)
        b = build_invocation_identity(mode=MODE_SYNC_STREAMING, **common)
        self.assertNotEqual(a.hash_sha256, b.hash_sha256)

    def test_format_participates_in_hash_isolated_construction(self):
        request = {"model": "shared-model", "messages": [{"role": "user", "content": "hi"}]}
        v1_material = {
            "format": INVOCATION_FORMAT,
            "surface": SURFACE_ANTHROPIC_MESSAGES,
            "mode": MODE_SYNC_NON_STREAMING,
            "request": request,
        }
        other_material = {**v1_material, "format": "aelitium-invocation-v2"}

        v1_hash = sha256_hash(canonical_json(v1_material))
        other_hash = sha256_hash(canonical_json(other_material))
        self.assertNotEqual(v1_hash, other_hash)

        identity = build_invocation_identity(
            surface=SURFACE_ANTHROPIC_MESSAGES,
            mode=MODE_SYNC_NON_STREAMING,
            model="shared-model",
            messages=[{"role": "user", "content": "hi"}],
        )
        self.assertEqual(identity.hash_sha256, v1_hash)

    def test_parser_rejects_unknown_format(self):
        identity = _build()
        stored = identity.to_stored_object()
        stored["format"] = "aelitium-invocation-v2"
        with self.assertRaises(InvocationIdentityError) as ctx:
            parse_invocation_identity(stored)
        self.assertEqual(ctx.exception.reason, "INVOCATION_BAD_FORMAT")


